def build_parser() -> argparse.ArgumentParser:
    ap = argparse.ArgumentParser(prog="llm-gateway", description="Hardened self-hosted LLM gateway and config auditor")
    ap.add_argument("--version", action="version", version=__version__)
    ap.add_argument("--env-file", help="load settings from this .env file (default: ./.env if present)")
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("init", help="generate strong secrets into .env (chmod 600)")
    p.add_argument("--force", action="store_true")
    p.set_defaults(fn=cmd_init)
    sub.add_parser("preflight", help="run start-up security checks").set_defaults(fn=cmd_preflight)
    p = sub.add_parser("serve", help="run the gateway (refuses to start with weak secrets)")
    p.add_argument("--host")
    p.add_argument("--port", type=int)
    p.set_defaults(fn=cmd_serve)
    p = sub.add_parser("keys", help="create, list, revoke or rotate per-user API keys")
    ks = p.add_subparsers(dest="action", required=True)
    k = ks.add_parser("create")
    k.add_argument("user")
    k.add_argument("--models", help="comma-separated allow-list (default: gateway list)")
    k.add_argument("--rpm", type=int, default=30)
    k.add_argument("--daily-tokens", type=int, default=200_000)
    k.add_argument("--ttl-days", type=float, default=90)
    k.add_argument("--note")
    ks.add_parser("list")
    ks.add_parser("revoke").add_argument("key_id")
    ks.add_parser("rotate").add_argument("key_id")
    p.set_defaults(fn=cmd_keys)
    p = sub.add_parser("audit-config", help="scan LiteLLM / Open WebUI / Ollama / compose configs")
    p.add_argument("paths", nargs="+")
    p.add_argument("--json", action="store_true")
    p.add_argument("--fail-on", choices=["HIGH", "MEDIUM", "LOW", "never"], default="HIGH")
    p.set_defaults(fn=cmd_audit_config)
    p = sub.add_parser("check-exposure", help="read-only check of your own endpoint for unauthenticated access")
    p.add_argument("url")
    p.add_argument("--json", action="store_true")
    p.set_defaults(fn=cmd_check_exposure)
    p = sub.add_parser("logs", help="verify, tail or analyse the JSONL audit log")
    p.add_argument("action", choices=["verify", "report", "tail"])
    p.add_argument("--log")
    p.add_argument("--json", action="store_true")
    p.add_argument("-n", type=int, default=20)
    p.set_defaults(fn=cmd_logs)
    p = sub.add_parser("ask", help="send one chat request through a running gateway")
    p.add_argument("prompt")
    p.add_argument("--url", default="http://127.0.0.1:8088")
    p.add_argument("--key", help="API key (or env GATEWAY_API_KEY)")
    p.add_argument("--model", default="qwen2.5-coder:3b")
    p.add_argument("--max-tokens", type=int, default=200)
    p.set_defaults(fn=cmd_ask)
    sub.add_parser("demo", help="offline walkthrough with a mock model").set_defaults(fn=cmd_demo)
    return ap


def main(argv=None) -> int:
    args = build_parser().parse_args(argv)
    return args.fn(args)
